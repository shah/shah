function detectManager(ctx: Context): PackageManager | undefined {
  const PATH = ctx.env.PATH ?? "";
  if (ctx.platform === "windows")
    return Bun.which("winget", { PATH }) ? "winget" : undefined;
  if (ctx.platform === "macos") return "brew";
  if (ctx.omarchy) return "omarchy";
  let release = "";
  try {
    release = readFileSync("/etc/os-release", "utf8");
  } catch {
    /* unknown distribution */
  }
  const ids =
    (/^ID=(.*)$/m.exec(release)?.[1] ?? "") +
    " " +
    (/^ID_LIKE=(.*)$/m.exec(release)?.[1] ?? "");
  const id = ids.replaceAll('"', "");
  if (/\b(debian|ubuntu)\b/.test(id)) return "apt";
  if (/\b(fedora|rhel|centos)\b/.test(id)) return "dnf";
  if (/\barch\b/.test(id)) return "pacman";
  if (/\balpine\b/.test(id)) return "apk";
  if (/\b(suse|opensuse)\b/.test(id)) return "zypper";
  if (Bun.which("brew", { PATH })) return "brew";
  return undefined;
}

export function installCommand(
  manager: PackageManager,
  packages: string[],
): string {
  const list = packages.join(" ");
  switch (manager) {
    case "apt":
      return `sudo apt install -y ${list}`;
    case "dnf":
      return `sudo dnf install -y ${list}`;
    case "pacman":
      return `sudo pacman -S --needed ${list}`;
    case "apk":
      return `sudo apk add ${list}`;
    case "zypper":
      return `sudo zypper install -y ${list}`;
    case "brew":
      return `brew install ${list}`;
    case "winget":
      return packages.map((p) => `winget install --id ${p} -e`).join("; ");
    case "omarchy":
      return packages
        .map((p) =>
          p === "oh-my-posh"
            ? "omarchy pkg aur add oh-my-posh-bin"
            : `omarchy pkg add ${p}`,
        )
        .join("; ");
    default:
      return assertNever(manager);
  }
}

type Check = {
  check: string;
  status: "ok" | "warn" | "missing";
  detail: string;
};

async function doctor(ctx: Context): Promise<{
  checks: Check[];
  advice: string[];
  platform: Platform;
  manager?: PackageManager;
}> {
  const checks: Check[] = [];
  const PATH = ctx.env.PATH ?? "";
  checks.push({
    check: "bun",
    status: versionAtLeast(Bun.version, minimumBun) ? "ok" : "missing",
    detail: `Bun ${Bun.version} (needs ${minimumBun} or newer)`,
  });
  try {
    const { source } = await loadConfig(ctx);
    checks.push({
      check: "config",
      status: source ? "ok" : "warn",
      detail: source
        ? `${tilde(ctx, ctx.configFile)} is valid`
        : "not created yet; run snshah apply",
    });
  } catch (error) {
    checks.push({
      check: "config",
      status: "missing",
      detail: (error as Error).message,
    });
  }
  const onPath = PATH.split(delimiter).some(
    (d) => resolve(d) === resolve(ctx.binDir),
  );
  checks.push({
    check: "path",
    status: onPath ? "ok" : "warn",
    detail: onPath
      ? `${tilde(ctx, ctx.binDir)} is on PATH`
      : `${tilde(ctx, ctx.binDir)} is not on PATH yet; open a new shell after snshah apply`,
  });
  const manager = detectManager(ctx);
  const missing: Tool[] = [];
  for (const tool of tools) {
    if (tool.linuxOnly && !(ctx.platform === "linux" || ctx.platform === "wsl"))
      continue;
    const found = Bun.which(tool.name, { PATH });
    if (!found) missing.push(tool);
    checks.push({
      check: tool.name,
      status: found ? "ok" : tool.required ? "missing" : "warn",
      detail: found ? tool.purpose : `not installed (${tool.purpose})`,
    });
  }
  const advice: string[] = [];
  const viaManager = missing
    .filter((t) => manager && t.advice[manager])
    .map((t) => t.advice[manager!]!);
  if (manager && viaManager.length)
    advice.push(installCommand(manager, viaManager));
  for (const tool of missing)
    if (!(manager && tool.advice[manager]) && tool.advice.fallback)
      advice.push(tool.advice.fallback);
  for (const tool of missing)
    if (!(manager && tool.advice[manager]) && !tool.advice.fallback)
      advice.push(`Install ${tool.name} with your package manager.`);
  return { checks, advice, platform: ctx.platform, manager };
}

